#!/usr/bin/env python3
"""Assemble the host-loadable firmware images into host/tempo_host/images.py.

Each image in IMAGES is a firmware file in fw/. Labels starting with `P_`
mark the parameter block: the host patches those words before starting
the threads (see host/tempo_host/link.py `Link.load`). Labels starting with `K_`
are exported as constants the host code may need (e.g. reply codes).

Run: python tools/gen_images.py        (writes the file)
     python tools/gen_images.py --check (fails if the file is stale)
"""

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from tempo import asm  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..")
FW = os.path.join(ROOT, "fw")
OUT = os.path.join(ROOT, "host", "tempo_host", "images.py")

IMAGES = ["i2c", "spi", "uart", "autobaud", "jtag", "swd", "la", "trigger", "i2cmon", "i2ctarget", "gpio"]


def build(name):
    path = os.path.join(FW, name + ".s")
    with open(path) as f:
        prog = asm.assemble(f.read(), FW)
    used = sorted(prog.used)
    base, top = used[0], used[-1]
    params = {k[2:].lower(): v for k, v in prog.symbols.items() if k.startswith("P_") and v in prog.used}
    consts = {k[2:].lower(): v for k, v in prog.symbols.items() if k.startswith("K_")}
    return {
        "name": name,
        "base": base,
        "words": prog.words[base:top + 1],
        "entry": dict(sorted(prog.entries.items())),
        "params": dict(sorted(params.items())),
        "consts": dict(sorted(consts.items())),
    }


def render(images):
    lines = ['# SPDX-License-Identifier: Apache-2.0',
             '"""Firmware images for Tempo. Generated by tools/gen_images.py from fw/; do not edit."""',
             '', 'IMAGES = {}', '']
    for im in images:
        ws = im["words"]
        lines.append("IMAGES[%r] = {" % im["name"])
        lines.append("    'name': %r," % im["name"])
        lines.append("    'base': %d," % im["base"])
        lines.append("    'entry': %r," % im["entry"])
        lines.append("    'params': %r," % im["params"])
        lines.append("    'consts': %r," % im["consts"])
        lines.append("    'words': [")
        for i in range(0, len(ws), 12):
            lines.append("        " + ", ".join("0x%04x" % w for w in ws[i:i + 12]) + ",")
        lines.append("    ],")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main():
    names = [n for n in IMAGES if os.path.exists(os.path.join(FW, n + ".s"))]
    text = render([build(n) for n in names])
    if "--check" in sys.argv:
        with open(OUT) as f:
            if f.read() != text:
                sys.exit("host/tempo_host/images.py is stale; run tools/gen_images.py")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s (%s)" % (OUT, ", ".join(names)))


if __name__ == "__main__":
    main()
