; Benchmark firmware: software bit-banged UART TX against lane UART TX on
; the same core and clock. Used by tools/bench_swlane.py, which starts one
; of the T0 entry points below and optionally `busy` on T1-T3.
;
; 8N1, LSB first, continuous stream. Bit period P_PER + P_FRAC/256 cycles,
; patched by the bench. Channel A is uio0, channel B (dual variants) uio1.
;
;   sw_main     software: waitt deadline + iow on GOUT, bytes from H2T.
;               FRAC = 0 uses the integer loop, otherwise the loop with a
;               software fractional accumulator.
;   lane_main   lane 0 tx, bytes from H2T, blocks in tx while the queue is full
;   lpoll_main  lane 0 tx, polls STAT.QFULL and counts background work in r7
;   swdual_main two software UARTs on one thread (A: P_PER, B: P_PERB),
;               earliest deadline first, generated bytes
;   ldual_main  two lane UARTs (lanes 0 and 1) on one thread, generated bytes

        .include "tempo.inc"

        .entry 0, sw_main
        .entry 1, busy
        .entry 2, busy
        .entry 3, busy

; ------------------------------------------------------------ software
; r0 0 (start level), r1 fraction accumulator, r2 period, r3 bit count,
; r4 data, r5 next edge deadline, r6 pin mask (also the stop level),
; r7 fraction << 8
sw_main:
        lc   r0, P_PER
        ldi  r2, [r0 + 0]
        ldi  r7, [r0 + 1]
        shli r7, r7, 8
        li   r6, 1
        iow  r6, r6                    ; idle high
        ioe  r6, r6
        li   r0, 0
        li   r1, 0
        now  r5
        addi r5, 200
        cmpi r7, 0
        bne  sf_byte

si_byte:
        hget r4
        waitt r5
        iow  r0, r6                    ; start bit
        add  r5, r5, r2
        li   r3, 8
si_bit: waitt r5
        iow  r4, r6
        shri r4, r4, 1
        add  r5, r5, r2
        djnz r3, si_bit
        waitt r5
        iow  r6, r6                    ; stop bit
        add  r5, r5, r2
        bra  si_byte

sf_byte:
        hget r4
        waitt r5
        iow  r0, r6                    ; start bit
        add  r5, r5, r2
        add  r1, r1, r7
        bcc  sf_s1
        addi r5, 1
sf_s1:  li   r3, 8
sf_bit: waitt r5
        iow  r4, r6
        shri r4, r4, 1
        add  r5, r5, r2
        add  r1, r1, r7
        bcc  sf_b1
        addi r5, 1
sf_b1:  djnz r3, sf_bit
        waitt r5
        iow  r6, r6                    ; stop bit
        add  r5, r5, r2
        add  r1, r1, r7
        bcc  sf_byte
        addi r5, 1
        bra  sf_byte

; ------------------------------------------------------------ lane
lane_setup:                            ; lane 0 on uio0, P_PER/P_FRAC; clobbers r0, r1
        lc   r0, P_PER
        lc   r1, NOPIN << 12 | NOPIN << 8 | NOPIN << 4 | UIO0
        lw   l0, pins, r1
        ldi  r1, [r0 + 0]
        lw   l0, len0, r1
        lw   l0, len1, r1
        ldi  r1, [r0 + 1]
        lw   l0, frac, r1
        lc   r1, SYM_NRZ1
        lw   l0, sym1, r1
        li   r1, E_D | E_DEN
        emit l0, r1                    ; idle high for one slot
        ret

lane_main:
        call lane_setup
        lc   r3, 0x0200
l_byte: hget r4
        shli r4, r4, 1
        or   r4, r4, r3
        tx   l0, r4, 10
        bra  l_byte

lpoll_main:
        call lane_setup
        lc   r3, 0x0200
        li   r7, 0
lp_loop:
        stat r1, l0
        andi r1, ST_QFULL
        bne  lp_work
        hget r4
        shli r4, r4, 1
        or   r4, r4, r3
        tx   l0, r4, 10
        bra  lp_loop
lp_work:
        addi r7, 1                     ; one unit of background work
        bra  lp_loop

; ------------------------------------------------------------ two channels
; scratch: [0] period A, [1] period B, [2] last byte A, [3] last byte B,
; [4] stop bit 0x200. r0 frame A, r1 frame B (bit 0 is the next level;
; reloaded when the stop bit has been shifted out), r5 deadline A,
; r2 deadline B, r3 mask A, r7 mask B, r6 scratch base 0.
; Each edge: wait, write, then advance; the frame reload runs after the
; edge, in the slack before the next deadline.
swdual_main:
        li   r6, 0
        lc   r0, P_PER
        ldi  r1, [r0 + 0]
        st   r1, [r6 + 0]
        ldi  r1, [r0 + 2]
        st   r1, [r6 + 1]
        lc   r1, P_SEEDA
        ldi  r1, [r1 + 0]
        st   r1, [r6 + 2]
        lc   r1, P_SEEDB
        ldi  r1, [r1 + 0]
        st   r1, [r6 + 3]
        lc   r1, 0x0200
        st   r1, [r6 + 4]
        li   r3, 1
        li   r7, 2
        li   r0, 3
        iow  r0, r0                    ; both idle high
        ioe  r0, r0
        li   r0, 1                     ; one idle bit, then the first frame
        li   r1, 1
        now  r5
        addi r5, 200
        mov  r2, r5
        addi r2, 100
sd_loop:
        cmp  r5, r2
        bpl  sd_b                      ; A is not earlier
        waitt r5
        iow  r0, r3
        ld   r4, [r6 + 0]
        add  r5, r5, r4
        shri r0, r0, 1
        bne  sd_loop
        ld   r4, [r6 + 2]              ; next byte A
        addi r4, 1
        andi r4, 0xFF
        st   r4, [r6 + 2]
        shli r0, r4, 1
        ld   r4, [r6 + 4]
        or   r0, r0, r4
        bra  sd_loop
sd_b:   shli r4, r1, 1                 ; level to bit 1
        waitt r2
        iow  r4, r7
        ld   r4, [r6 + 1]
        add  r2, r2, r4
        shri r1, r1, 1
        bne  sd_loop
        ld   r4, [r6 + 3]              ; next byte B
        addi r4, 1
        andi r4, 0xFF
        st   r4, [r6 + 3]
        shli r1, r4, 1
        ld   r4, [r6 + 4]
        or   r1, r1, r4
        bra  sd_loop

ldual_main:
        call lane_setup
        lc   r0, P_PER
        lc   r1, NOPIN << 12 | NOPIN << 8 | NOPIN << 4 | (UIO0 + 1)
        lw   l1, pins, r1
        ldi  r1, [r0 + 2]
        lw   l1, len0, r1
        lw   l1, len1, r1
        ldi  r1, [r0 + 3]
        lw   l1, frac, r1
        lc   r1, SYM_NRZ1
        lw   l1, sym1, r1
        li   r1, E_D | E_DEN
        emit l1, r1
        lc   r1, P_SEEDA
        ldi  r5, [r1 + 0]
        lc   r1, P_SEEDB
        ldi  r6, [r1 + 0]
        lc   r3, 0x0200
        li   r7, 0
ld_loop:
        stat r1, l0
        andi r1, ST_QFULL
        bne  ld_b
        addi r5, 1
        andi r5, 0xFF
        shli r4, r5, 1
        or   r4, r4, r3
        tx   l0, r4, 10
ld_b:   stat r1, l1
        andi r1, ST_QFULL
        bne  ld_work
        addi r6, 1
        andi r6, 0xFF
        shli r4, r6, 1
        or   r4, r4, r3
        tx   l1, r4, 10
        bra  ld_loop
ld_work:
        addi r7, 1                     ; background work
        bra  ld_loop

; ------------------------------------------------------------ load
; Other threads: ALU, scratch, IMEM data reads and GOUT writes to a pin
; neither UART uses.
busy:   tid  r1
        addi r1, 4
        lc   r2, 1 << 7
busy_l: addi r0, 1
        st   r0, [r1 + 0]
        ld   r3, [r1 + 0]
        ldi  r4, [r1 + 0]
        iow  r0, r2
        bra  busy_l

P_PER:   .word 217                     ; A: integer cycles per bit
P_FRAC:  .word 4                       ; A: fraction, 1/256 cycle
P_PERB:  .word 250                     ; B: integer cycles per bit
P_FRACB: .word 0                       ; B: fraction (lanes only)
P_SEEDA: .word 0x40
P_SEEDB: .word 0xA0
